"""Reference-led body refinements in native integer coordinates.

Original face/hair layers are retained. Garments are never painted on the body.
"""
from PIL import Image, ImageDraw
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parent
PALETTE=list(json.loads((ROOT/'palette.json').read_text()).values())


def refine(parts,bones,revision=5):
    by_name={b['name']:b for b in bones}
    def draw(name,pivot,end,clusters):
        im=Image.new('RGBA',(64,96));d=ImageDraw.Draw(im)
        for color,polygon in clusters:
            d.polygon([(x+19,y+20) for x,y in polygon],fill=PALETTE[color])
        parts[name]=im
        by_name[name].update(pivot=[pivot[0]+19,pivot[1]+20],end=[end[0]+19,end[1]+20])
    draw('neck',(14,14),(14,11),[
      (3,[(13,10),(16,10),(16,12),(15,13),(16,15),(13,16),(11,14),(13,12)]),
      (4,[(13,11),(15,11),(14,13),(15,15),(13,15),(12,14)]),
      (5,[(13,12),(14,12),(14,14),(13,14)])])
    draw('torso',(13,22),(12,15),[
      (4,[(11,13),(14,13),(16,14),(18,16),(19,17),(19,19),(17,21),(16,23),(12,23),(10,21),(9,17),(9,15)]),
      (5,[(11,14),(13,14),(15,16),(17,16),(18,18),(17,19),(14,20),(13,22),(11,21),(11,18),(10,16)]),
      (6,[(17,20),(18,19),(17,22),(15,23),(13,23),(13,22),(16,21)]),
      (4,[(11,16),(12,17),(12,19),(13,20),(12,20),(10,18)]),
      (5,[(14,21),(16,21),(15,22),(14,22)])])
    draw('abdomen',(13,27),(13,22),[
      (4,[(11,21),(16,21),(17,23),(16,25),(17,27),(15,29),(11,28),(10,26),(11,24)]),
      (5,[(12,22),(15,22),(15,24),(14,26),(15,27),(12,28),(11,26),(12,24)]),
      (6,[(16,23),(16,25),(17,27),(15,28),(15,26)]),
      (4,[(12,25),(14,25),(14,26),(12,26)])])
    draw('pelvis',(13,28),(13,31),[
      (4,[(11,25),(15,25),(17,26),(19,28),(19,30),(17,33),(14,34),(10,33),(8,31),(8,29),(9,27)]),
      (5,[(11,26),(14,26),(15,28),(14,30),(13,33),(10,32),(9,30),(9,28)]),
      (6,[(17,27),(18,28),(18,31),(16,33),(14,33),(15,31),(16,29)]),
      (4,[(14,26),(16,27),(16,29),(14,30)])])
    draw('arm_far',(16,16),(16,23),[
      (3,[(15,15),(17,15),(18,17),(18,20),(17,24),(15,25),(14,22),(15,19)]),
      (4,[(16,16),(17,17),(17,20),(16,23),(15,23),(16,20)])])
    draw('forearm_far',(16,23),(16,30),[
      (3,[(15,22),(17,22),(18,24),(17,28),(17,31),(15,32),(14,29)]),
      (4,[(16,23),(17,24),(16,28),(16,30),(15,30),(15,28)])])
    draw('hand_far',(16,30),(16,34),[
      (3,[(15,29),(17,29),(17,32),(18,33),(17,35),(15,34),(14,32)]),
      (4,[(15,30),(16,30),(16,32),(17,33),(16,34),(15,32)])])
    draw('arm_near',(9,16),(7,23),[
      (4,[(8,14),(10,14),(11,16),(11,18),(9,21),(9,23),(8,25),(6,24),(6,21),(7,18),(7,16)]),
      (5,[(8,15),(9,15),(10,16),(10,18),(8,20),(8,23),(6,23),(7,20),(8,18)]),
      (6,[(9,19),(10,18),(9,22),(8,24),(7,24),(8,21)]),
      (4,[(7,19),(9,19),(8,21),(7,21)])])
    draw('forearm_near',(7,23),(6,30),[
      (4,[(6,22),(8,22),(9,24),(8,26),(8,29),(7,31),(5,32),(4,30),(5,27),(5,24)]),
      (5,[(6,23),(7,23),(7,26),(6,28),(6,31),(5,31),(5,29),(6,26)]),
      (6,[(8,25),(8,28),(7,30),(7,31),(6,31),(7,28)]),
      (4,[(5,29),(6,29),(6,30),(5,31)])])
    draw('hand_near',(6,30),(5,34),[
      (4,[(5,29),(7,30),(7,31),(8,32),(7,33),(6,32),(6,35),(4,35),(3,33),(4,31)]),
      (5,[(5,30),(6,30),(5,32),(5,34),(4,34),(4,32)]),
      (6,[(6,33),(6,35),(5,35)]),
      (4,[(4,31),(5,31),(4,33)])])
    draw('thigh_near',(11,30),(9,41),[
      (4,[(9,29),(12,28),(14,30),(14,33),(13,36),(12,39),(11,42),(8,43),(7,41),(8,37),(7,34),(7,31)]),
      (5,[(9,30),(11,30),(12,32),(12,35),(10,38),(10,41),(8,42),(8,40),(9,36),(8,34),(8,32)]),
      (6,[(13,33),(13,36),(11,40),(11,42),(9,42),(10,38),(11,36)]),
      (4,[(8,36),(10,36),(9,39),(8,40)])])
    draw('shin_near',(9,41),(8,52),[
      (4,[(8,40),(10,40),(11,42),(10,44),(10,47),(9,50),(9,53),(7,54),(6,52),(6,49),(7,46),(6,44),(6,42)]),
      (5,[(8,41),(9,41),(9,44),(8,46),(8,49),(7,52),(7,50),(7,47),(7,44)]),
      (6,[(10,44),(10,47),(8,51),(8,53),(7,53),(8,49),(9,47)]),
      (4,[(7,45),(8,45),(8,47),(7,48)])])
    draw('foot_near',(8,52),(11,55),[
      (4,[(7,51),(9,51),(9,53),(10,54),(12,54),(13,55),(7,55),(6,54),(6,53)]),
      (5,[(7,52),(8,52),(8,53),(10,54),(11,54),(9,54),(7,54)]),
      (6,[(7,55),(11,55),(12,55)]),
      (4,[(6,54),(7,53),(7,54)])])
    draw('thigh_far',(16,30),(15,41),[
      (3,[(14,29),(17,29),(19,31),(18,34),(18,37),(17,40),(17,43),(14,43),(13,40),(14,36),(13,32)]),
      (4,[(15,30),(17,31),(17,34),(16,38),(16,41),(14,42),(14,39),(15,35),(14,32)]),
      (6,[(17,34),(18,33),(18,37),(16,41),(16,43),(15,42),(16,39)]),
      (5,[(14,32),(15,32),(15,35),(14,36)])])
    draw('shin_far',(15,41),(16,52),[
      (3,[(14,40),(16,40),(17,42),(18,44),(18,47),(17,50),(17,53),(15,54),(14,52),(15,48),(14,45),(13,43)]),
      (4,[(15,41),(16,42),(17,44),(17,46),(16,50),(16,53),(15,52),(16,48),(15,45),(14,43)]),
      (6,[(17,47),(17,50),(16,52),(16,53),(15,51),(16,49)])])
    draw('foot_far',(16,52),(20,55),[
      (3,[(15,51),(17,51),(17,53),(19,54),(21,54),(21,55),(15,55),(14,54)]),
      (4,[(16,52),(17,53),(18,54),(20,54),(19,54),(16,54),(15,54)]),
      (6,[(15,55),(18,55),(20,55)])])
    if revision>=5:
        # Retain selected real skin clusters from the supplied reference; no
        # shirt, shorts, boots, or palette conversion is copied onto the body.
        ref=Image.open(ROOT/'references/body_reference.png').convert('RGBA')
        skin={tuple(bytes.fromhex(PALETTE[i][1:]))+(255,) for i in [3,4,5,6,9]}
        for name,box in [('thigh_near',(8,34,13,40)),('shin_near',(7,40,11,44)),('thigh_far',(14,34,18,40))]:
            im=parts[name]
            for y in range(box[1],box[3]):
                for x in range(box[0],box[2]):
                    color=ref.getpixel((x,y))
                    if color in skin and im.getpixel((x+19,y+20))[3]: im.putpixel((x+19,y+20),color)
        # Elbow/wrist joins and abdomen cleaned locally, keeping light continuous.
        for name,clusters in {
          'forearm_near':[(5,[(6,22),(7,23),(7,24),(6,24)]),(4,[(8,23),(8,25)])],
          'shin_near':[(5,[(8,40),(9,40),(9,42),(8,43)]),(4,[(9,43),(10,42),(10,44)])],
          'abdomen':[(5,[(12,23),(14,23),(14,24),(13,25),(12,25)]),(4,[(14,26),(15,26),(15,27)])],
          'hand_near':[(5,[(5,31),(5,33)]),(4,[(4,34),(5,34)])],
        }.items():
            d=ImageDraw.Draw(parts[name])
            for color,poly in clusters:d.polygon([(x+19,y+20) for x,y in poly],fill=PALETTE[color])
    return parts,bones
